//! Compile-time checks for WGSL shaders, for build scripts.
//!
//! [`check`] parses and validates every `.wgsl` file in a folder with naga,
//! the shader compiler wgpu itself uses, so a shader error fails
//! `cargo build` with naga's message, pointing at the file and line. It
//! also writes `$OUT_DIR/shaders.rs`, with each shader's source and the size
//! of its uniform block, so Rust structs are checked against the shader
//! with a `const` assertion: a mismatch is a compile error, not a GPU
//! validation error at the first draw.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

/// Checks every `.wgsl` file in `dir` (relative to the crate) and writes
/// `$OUT_DIR/shaders.rs`. For `boxes.wgsl` it holds `BOXES` (the source)
/// and, if the shader has a uniform block, `BOXES_UNIFORM` (its size in
/// bytes). Panics, failing the build, if any shader does not compile.
pub fn check(dir: &str) {
    let root =
        PathBuf::from(std::env::var_os("CARGO_MANIFEST_DIR").expect("run from a build script"));
    let out = PathBuf::from(std::env::var_os("OUT_DIR").expect("run from a build script"));
    println!("cargo::rerun-if-changed={dir}");
    let mut paths: Vec<PathBuf> = std::fs::read_dir(root.join(dir))
        .unwrap_or_else(|e| panic!("reading {dir}: {e}"))
        .filter_map(|entry| entry.ok().map(|e| e.path()))
        .filter(|path| path.extension().is_some_and(|e| e == "wgsl"))
        .collect();
    paths.sort();
    let mut code = String::from("// Generated by lumen-shader-check from the .wgsl files.\n");
    let mut errors = Vec::new();
    for path in &paths {
        println!("cargo::rerun-if-changed={}", path.display());
        let source = std::fs::read_to_string(path)
            .unwrap_or_else(|e| panic!("reading {}: {e}", path.display()));
        let shown = path.strip_prefix(&root).unwrap_or(path);
        match check_source(&source, &shown.display().to_string()) {
            Ok(uniform) => {
                let name = constant_name(path);
                let _ = writeln!(code, "pub const {name}: &str = include_str!({path:?});");
                if let Some(size) = uniform {
                    let _ = writeln!(code, "pub const {name}_UNIFORM: usize = {size};");
                }
            }
            Err(message) => errors.push(message),
        }
    }
    if !errors.is_empty() {
        for message in &errors {
            eprintln!("{message}");
        }
        panic!(
            "{} shader(s) did not compile; naga's messages are above",
            errors.len()
        );
    }
    std::fs::write(out.join("shaders.rs"), code).expect("writing shaders.rs");
}

/// Parses and validates one shader (`path` is only for messages); returns
/// the size of its uniform block, if it has one.
pub fn check_source(source: &str, path: &str) -> Result<Option<u32>, String> {
    let module = naga::front::wgsl::parse_str(source)
        .map_err(|e| e.emit_to_string_with_path(source, path))?;
    naga::valid::Validator::new(
        naga::valid::ValidationFlags::all(),
        naga::valid::Capabilities::empty(),
    )
    .validate(&module)
    .map_err(|e| e.emit_to_string_with_path(source, path))?;
    let mut layouter = naga::proc::Layouter::default();
    layouter
        .update(module.to_ctx())
        .map_err(|e| format!("{path}: {e}"))?;
    let uniforms: Vec<u32> = module
        .global_variables
        .iter()
        .filter(|(_, var)| var.space == naga::AddressSpace::Uniform)
        .map(|(_, var)| layouter[var.ty].size)
        .collect();
    match uniforms.as_slice() {
        [] => Ok(None),
        [size] => Ok(Some(*size)),
        _ => Err(format!(
            "{path}: more than one uniform block; the checker reports one per shader"
        )),
    }
}

/// `boxes.wgsl` → `BOXES`, `ui-stress.wgsl` → `UI_STRESS`.
fn constant_name(path: &Path) -> String {
    path.file_stem()
        .map(|s| {
            s.to_string_lossy()
                .to_uppercase()
                .replace(['-', ' ', '.'], "_")
        })
        .unwrap_or_default()
}

#[cfg(test)]
mod tests {
    use super::*;

    const GOOD: &str = r"
struct U { size: vec2<f32>, scale: f32, top: f32 };
@group(0) @binding(0) var<uniform> u: U;
@vertex fn vs_main() -> @builtin(position) vec4<f32> { return vec4<f32>(u.size, u.scale, u.top); }
";

    #[test]
    fn a_good_shader_reports_its_uniform_size() {
        assert_eq!(check_source(GOOD, "good.wgsl"), Ok(Some(16)));
    }

    #[test]
    fn a_shader_error_names_the_file_and_line() {
        let bad = GOOD.replace("u.scale", "u.missing");
        let message = check_source(&bad, "bad.wgsl").unwrap_err();
        assert!(message.contains("bad.wgsl:4"), "{message}");
        assert!(message.contains("missing"), "{message}");
    }

    #[test]
    fn a_vec3_pad_is_measured_as_the_gpu_lays_it_out() {
        // The padding bug of slice 4c: a vec3 aligns to 16 bytes, so after
        // three floats it starts at byte 16, and the block takes 32.
        let shader = r"
struct U { a: f32, b: f32, c: f32, pad: vec3<f32> };
@group(0) @binding(0) var<uniform> u: U;
@vertex fn vs_main() -> @builtin(position) vec4<f32> { return vec4<f32>(u.a); }
";
        assert_eq!(check_source(shader, "pad.wgsl"), Ok(Some(32)));
    }

    #[test]
    fn names_become_constants() {
        assert_eq!(
            constant_name(Path::new("src/shaders/ui-stress.wgsl")),
            "UI_STRESS"
        );
        assert_eq!(constant_name(Path::new("boxes.wgsl")), "BOXES");
    }
}
